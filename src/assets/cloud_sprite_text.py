PixelRows = tuple[str, ...]
ALLOWED_PIXEL_CHARS = frozenset("0123456789ABCDEF")


@dataclass(frozen=True, slots=True)
class CloudSpriteVariants:
    variant_0: PixelRows
    variant_1: PixelRows
    variant_2: PixelRows

    def at(self, variant: int) -> PixelRows:
        if not 0 <= variant < CLOUD_SPRITE_VARIANT_COUNT:
            raise ValueError(f"unknown cloud sprite variant: {variant}")
        return (self.variant_0, self.variant_1, self.variant_2)[variant]


def _rows(*rows: str) -> PixelRows:
    return tuple(row.upper() for row in rows)



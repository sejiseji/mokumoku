def validate_pixel_rows(
    rows: PixelRows,
    *,
    expected_width: int,
    expected_height: int,
) -> None:
    if len(rows) != expected_height:
        raise ValueError(
            "invalid sprite height: "
            f"expected={expected_height}, actual={len(rows)}"
        )

    for row_index, row in enumerate(rows):
        if len(row) != expected_width:
            raise ValueError(
                f"invalid sprite width at row {row_index}: "
                f"expected={expected_width}, actual={len(row)}"
            )

        invalid = set(row) - ALLOWED_PIXEL_CHARS
        if invalid:
            raise ValueError(
                f"invalid pixel characters at row {row_index}: "
                f"{sorted(invalid)}"
            )


def validate_family_palette(
    family: CloudSpriteFamily,
    rows: PixelRows,
) -> None:
    used = set("".join(rows))
    invalid = used - FAMILY_ALLOWED_COLORS[family]
    if invalid:
        raise ValueError(
            f"{family.value} uses forbidden colors: {sorted(invalid)}"
        )


def opaque_positions(rows: PixelRows) -> set[tuple[int, int]]:
    return {
        (x, y)
        for y, row in enumerate(rows)
        for x, char in enumerate(row)
        if char != "0"
    }


def opaque_centroid(rows: PixelRows) -> tuple[float, float]:
    positions = opaque_positions(rows)
    if not positions:
        raise ValueError("sprite contains no opaque pixels")

    count = len(positions)
    return (
        sum(x for x, _ in positions) / count,
        sum(y for _, y in positions) / count,
    )


def opaque_bbox(rows: PixelRows) -> tuple[int, int, int, int]:
    positions = opaque_positions(rows)
    if not positions:
        raise ValueError("sprite contains no opaque pixels")

    xs = [x for x, _ in positions]
    ys = [y for _, y in positions]
    return min(xs), min(ys), max(xs), max(ys)


def validate_variant_geometry(
    variants: CloudSpriteVariants,
    *,
    center_tolerance: float = 0.35,
    bbox_tolerance: int = 1,
) -> None:
    base_rows = variants.variant_0
    base_center = opaque_centroid(base_rows)
    base_bbox = opaque_bbox(base_rows)

    for variant_index in (1, 2):
        rows = variants.at(variant_index)
        current_center = opaque_centroid(rows)
        current_bbox = opaque_bbox(rows)

        if abs(current_center[0] - base_center[0]) > center_tolerance:
            raise ValueError(
                f"variant {variant_index} shifts visual center on x: "
                f"{current_center[0] - base_center[0]:.3f}px"
            )
        if abs(current_center[1] - base_center[1]) > center_tolerance:
            raise ValueError(
                f"variant {variant_index} shifts visual center on y: "
                f"{current_center[1] - base_center[1]:.3f}px"
            )

        for base_value, current_value in zip(base_bbox, current_bbox, strict=True):
            if abs(current_value - base_value) > bbox_tolerance:
                raise ValueError(
                    f"variant {variant_index} changes opaque bbox too much: "
                    f"base={base_bbox}, current={current_bbox}"
                )


def validate_sprite_catalog() -> None:
    expected_keys = {
        (family, size_class)
        for family in CLOUD_FAMILY_ORDER
        for size_class in CLOUD_SIZE_ORDER
    }
    actual_keys = set(CLOUD_SPRITE_TEXT)

    missing = expected_keys - actual_keys
    extra = actual_keys - expected_keys
    if missing or extra:
        raise ValueError(
            "cloud sprite catalog mismatch: "
            f"missing={sorted((family.value, size) for family, size in missing)}, "
            f"extra={sorted((family.value, size) for family, size in extra)}"
        )

    for family in CLOUD_FAMILY_ORDER:
        for size_class in CLOUD_SIZE_ORDER:
            expected_size = CLOUD_SIZE_PIXELS[size_class]
            variants = CLOUD_SPRITE_TEXT[(family, size_class)]

            for variant in range(CLOUD_SPRITE_VARIANT_COUNT):
                rows = variants.at(variant)
                validate_pixel_rows(
                    rows,
                    expected_width=expected_size,
                    expected_height=expected_size,
                )
                validate_family_palette(family, rows)

            validate_variant_geometry(variants)
